const route={points:[{x:0,z:0},{x:0,z:3200}],length:3200,spawn:{distance:35}};
const surface=()=>0;
const player={x:0,z:100,vx:0,vz:22,heading:0,speed:22};
const makePursuer=(x,z,options={})=>({x,z,heading:0,speed:14,health:100,bank:0,...options});

test('avalanche leads a rear pursuer and corrects the impact within its original area',()=>{
  const run=new PatrolRun(route,()=>true,()=>false);
  const rear=makePursuer(-8,46),guard=makePursuer(0,65,{guardUntil:3}),ahead=makePursuer(0,120);
  run.agents=[rear,guard,ahead];run.inventory=['avalanche'];run.stars=1;
  assert.ok(run.use(player));
  const bomb=run.bombs[0];
  assert.equal(bomb.target,rear);
  assert.equal(bomb.end.x,-8);
  assert.ok(bomb.end.z>rear.z&&bomb.end.z<60);
  rear.z+=12;
  const blast=[];
  run.step(.6,player,()=>false,surface,()=>null,value=>blast.push(value)&&null);
  assert.equal(blast.length,1);
  assert.ok(Math.abs(blast[0].z-rear.z)<2);
});

test('trails follow the real path, catch a fast crossing, and break across airtime',()=>{
  const writer={flametrail:{last:{x:0,z:0},linger:4.5,extra:0}};
  const segments=layTrails([],writer,{x:0,z:10},.1);
  assert.equal(segments.length,3);
  assert.ok(trailContact(segments,{x:-10,z:5},{x:10,z:5},surface).flametrail);
  const crossed=layTrails(segments,writer,{x:0,z:23,airborne:true},.2);
  assert.equal(crossed.length,3);
  assert.equal(layTrails(crossed,writer,{x:0,z:23},4.7).length,0);
  const view=new ChaseTrailEffects(new THREE.Group());
  view.update(segments,surface,.2);
  assert.equal(view.layers.flametrail.plume.count,3);
  const ribbon=view.layers.flametrail.ribbon;
  const height=(x,z)=>.08*z*z+.2*x;
  const sloped=new ChaseTrailEffects(new THREE.Group());
  sloped.update(segments,height,.2);
  const ground=sloped.layers.flametrail.ribbon.geometry;
  const {position,expiry}=ground.attributes;
  assert.ok(ground.drawRange.count>18);
  const lastVertex=Math.max(...ground.index.array.subarray(0,ground.drawRange.count));
  for(let i=0;i<=lastVertex;i++)assert.ok(Math.abs(position.getY(i)-height(position.getX(i),position.getZ(i))-.045)<1e-6);
  assert.equal(expiry.getX(0),Math.fround(segments[0].until));
  sloped.update(segments,height,.5);
  assert.equal(sloped.clock.value,.5);
  assert.match(ribbon.material.fragmentShader,/float groove/);
  assert.equal(view.layers.frosttrail.ribbon.geometry.drawRange.count,0);
  view.update([],surface,5);
  assert.equal(view.layers.flametrail.plume.count,0);
  assert.equal(ribbon.geometry.drawRange.count,0);
});

test('frost and fire trigger a one-time thermal hit, and mirage feeds a separate follow-up',()=>{
  const run=new PatrolRun(route,()=>true,()=>false);
  const target=makePursuer(0,106);
  run.agents=[target];run.stars=1;
  run.inventory=['frosttrail','flametrail','miragetrail'];
  assert.ok(run.use(player));
  run.step(.11,{...player,z:109},()=>false);
  assert.equal(target.health,90);
  assert.ok(target.chillUntil>run.time);
  assert.ok(run.use(player));
  run.step(.11,{...player,z:109},()=>false);
  assert.equal(target.chillUntil,0);
  assert.equal(target.health,66);
  assert.equal(run.hits.at(-1).combo,'融裂');
  run.step(1.01,{...player,z:109},()=>false);
  assert.equal(target.health,58);
  assert.ok(run.use(player));
  run.step(.11,{...player,z:109},()=>false);
  assert.ok(target.mirage?.until>run.time);
  assert.ok(Math.abs(target.mirage.point.x)>8);
  assert.equal(target.health,49);
  assert.equal(run.damage(target,'autofrost',15),'hit');
  assert.equal(target.health,22);
  assert.equal(run.hits.at(-1).combo,'破幻');
  assert.equal(target.mirage,null);
});

test('Whitepeak stitches measured Annapurna relief to the local terrain and renders rock and snow',()=>{
  const {terrain}=createChaseMountain();
  const asset=readFileSync(new URL('../public/'+WHITEPEAK_RELIEF_PATH,import.meta.url));
  const bytes=asset.buffer.slice(asset.byteOffset,asset.byteOffset+asset.byteLength);
  const context=stitchWhitepeakRelief(bytes,terrain);
  assert.throws(()=>stitchWhitepeakRelief(new ArrayBuffer(8),terrain),/size/);
  assert.equal(context.spacing,96);
  assert.ok((context.width-1)*context.spacing>=61000);
  const middle=Math.floor(context.height/2)*context.width;
  assert.ok(context.heights.subarray(middle).some(elevation=>elevation>9550));
  const center=middle+Math.floor(context.width/2);
  assert.ok(Math.abs(context.heights[center]-terrain.sample(0,0))<.001);
  const far=center+180*context.width;
  assert.equal(context.heights[far],new DataView(bytes).getUint16(far*2,true));
  const scene=new THREE.Scene();
  const surfaceAsset=readFileSync(new URL('../public/'+WHITEPEAK_SURFACE_PATH,import.meta.url));
  assert.equal(surfaceAsset.toString('hex',0,8),'89504e470d0a1a0a');
  assert.equal(surfaceAsset.readUInt32BE(16),1024);
  assert.equal(surfaceAsset.readUInt32BE(20),1024);
  const surfaceTexture=new THREE.Texture();
  const backdrop=addWhitepeakBackdrop(scene,context,terrain,surfaceTexture);
  const backgroundFog={value:.000011};
  prepareAtmosphere(scene,{value:0},backgroundFog);
  const {vertexShader,fragmentShader}=THREE.ShaderLib.standard;
  const shader={vertexShader,fragmentShader,uniforms:{}};
  backdrop.material.onBeforeCompile(shader);
  assert.match(shader.vertexShader,/vRelief=position/);
  assert.match(shader.fragmentShader,/vec3 landform=texture2D/);
  assert.match(shader.fragmentShader,/stone=alpineVegetation/);
  const woodlands=scene.getObjectByName('Whitepeak slope woodlands');
  assert.ok(woodlands.children.length>8);
  const location=new THREE.Vector3(),matrix=new THREE.Matrix4();
  const halfX=(terrain.width-1)*terrain.spacing/2,halfZ=(terrain.height-1)*terrain.spacing/2;
  let treeCount=0;
  const meshDetails=new Set();
  for(const tile of woodlands.children){
    assert.ok(tile.isInstancedMesh&&tile.boundingSphere.radius>0);
    assert.ok(tile.geometry.attributes.position.count>8);
    meshDetails.add(tile.geometry.index.count);
    treeCount+=tile.count;
    for(const sample of [0,tile.count-1]){
      tile.getMatrixAt(sample,matrix);
      location.setFromMatrixPosition(matrix);
      assert.ok(Math.max(Math.abs(location.x)-halfX,Math.abs(location.z)-halfZ)>=79.99);
      assert.ok(location.y+1200<3900);
    }
  }
  assert.ok(treeCount>5000&&treeCount<80000);
  assert.equal(meshDetails.size,2);
  assert.match(shader.fragmentShader,/normal=normalize\(mix\(normal,reliefNormal/);
  assert.match(shader.fragmentShader,/float mistDensity=backgroundFogDensity/);
  const {west,east,north,south}=WHITEPEAK_SURFACE_BOUNDS;
  assert.deepEqual(shader.uniforms.reliefSurfaceBounds.value.toArray(),[west,north,east-west,south-north]);
  assert.equal(shader.uniforms.annapurnaSurface.value,surfaceTexture);
  assert.equal(shader.uniforms.backgroundFogDensity,backgroundFog);
  assert.equal(backdrop.material.vertexColors,true);
  assert.ok(backdrop.material.userData.distanceHaze<1);
  const colors=backdrop.geometry.attributes.color;
  assert.equal(colors.count,backdrop.geometry.attributes.position.count);
  assert.ok(colors.array.every(Number.isFinite));
  assert.ok(colors.array.some(color=>color>.85)&&colors.array.some(color=>color<.3));
});
